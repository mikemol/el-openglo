"""closure_tree.py — the closure declaration as a TREE, not one file (W662, under W660).

closures.bzl held every stage's closure in one file, so every port of a spec to pytestspec rewrote it and the
card leases clashed. The growing part is the `pytestspec` closure (it lists every spec's files), so that
closure is now a nested tree, and a port edits only its family's leaf:

    closures.bzl                          the root: loads the kinds, assembles CLOSURES and EXTRA_NAMED
    closures_selftest.bzl                 CLOSURES = {scripts/check_X.py: [files]} (one literal)
    closures_stages.bzl                   CLOSURES = {opa-test, segment-lattice, worklist, readme}
    closures_pytestspec.bzl               FILES = the machinery + every family
    closures_pytestspec_machinery.bzl     FILES = [files no spec owns: the runner, the libraries, ...]
    closures_pytestspec_<family>.bzl      FILES = its specs' files (family: custom.family in the rego METADATA)

A family leaf SPLITS into per-spec children by becoming a composite (a node that loads its children): only
that node changes, never its parent, the kind or the root. A new port edits its family's leaf; the root and
the kinds do not change. Each file is either a literal `FILES = [...]` or loads of its children
(`FILES = _f0 + _f1 + ...`): that is the whole Starlark subset the reader needs, so it is read with `ast`
and never run.

⚑ THE NODES LIVE IN THE ROOT PACKAGE, NOT UNDER closures/. select_tracked (mtools:rules_py/tracked.bzl) says a
tracked file under a directory with its own BUILD file belongs to THAT package and is not a label of this
one, so a closures/BUILD.bazel would make the repo-wide ALL list unresolvable. The tree is in the names.

    scripts/closure_tree.py --tree       # the nodes and their files, one per line (n of m)
    scripts/closure_tree.py --selftest

⚑ WEAKNESS, STATED. The reader follows the `load(...)` labels of a composite and ignores the `FILES = a + b`
expression itself, so a composite whose expression drops a loaded child reads as holding it; Bazel would not.
The partition is by file NAME (policy/NAME.rego, NAME_test.rego, NAME.cases.json belong to spec NAME); a file
a spec reads that is named otherwise lands in the machinery leaf.
"""

import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))

PYTESTSPEC = "pytestspec"
MACHINERY = "pytestspec_machinery"
KINDS = ("selftest", "stages")
SPEC_SUFFIXES = ("_test.rego", ".cases.json", ".rego")
PREFIX = "closures_"
HEADER = [
    "# SPDX-License-Identifier: Apache-2.0",
    "# Copyright (c) 2026 Mike Mol",
]
GENERATED = '"""GENERATED by scripts/check_closure.py --write (W662): never edit."""'


def node_path(name):
    return f"{PREFIX}{name}.bzl"


def node_label(name):
    return f":{PREFIX}{name}.bzl"


def spec_of(path, specs):
    """The spec a policy file belongs to, or None (a file outside policy/, or a stem that is no spec)."""
    if os.path.dirname(path) != "policy":
        return None
    base = os.path.basename(path)
    for suffix in SPEC_SUFFIXES:
        if base.endswith(suffix):
            stem = base[: -len(suffix)]
            return stem if stem in specs else None
    return None


def partition(files, family_of, specs=None, by_spec=False):
    """{leaf node name: sorted files}: the spec files in a leaf per family (or per SPEC when `by_spec`), the rest
    in the machinery.

    `specs` is the population of policy specs (default: the keys of `family_of`). A spec in the population
    with no family is a ValueError: it must not fall into the machinery unseen."""
    specs = set(family_of) if specs is None else set(specs)
    out = {MACHINERY: []}
    for path in sorted(set(files)):
        spec = spec_of(path, specs)
        if spec is None:
            out[MACHINERY].append(path)
        elif spec not in family_of:
            msg = f"{spec}: a policy spec with no family (set custom.family in its rego METADATA)"
            raise ValueError(msg)
        else:
            leaf = f"{PYTESTSPEC}_{family_of[spec]}" + (f"_{spec}" if by_spec else "")
            out.setdefault(leaf, []).append(path)
    return out


def render_leaf(files):
    lines = [*HEADER, GENERATED, "", "FILES = ["]
    lines += [f'    "{p}",' for p in files]
    return "\n".join([*lines, "]"]) + "\n"


def render_composite(children):
    lines = [*HEADER, GENERATED, ""]
    lines += [
        f'load("{node_label(c)}", _f{i} = "FILES")' for i, c in enumerate(children)
    ]
    names = " + ".join(f"_f{i}" for i in range(len(children)))
    return "\n".join([*lines, "", f"FILES = {names}"]) + "\n"


def render_dict(closures):
    lines = [*HEADER, GENERATED, "", "CLOSURES = {"]
    for key in sorted(closures):
        lines.append(f'    "{key}": [')
        lines += [f'        "{p}",' for p in closures[key]]
        lines.append("    ],")
    return "\n".join([*lines, "}"]) + "\n"


def render_root(extra_named):
    lines = [
        *HEADER,
        '"""GENERATED by scripts/check_closure.py --write (W493, W662): the root of the closure tree.',
        "A CLAIM, not a proof of completeness (the witness, W494, tests it). Never edit.",
        '"""',
        "",
        f'load("{node_label("selftest")}", _selftest = "CLOSURES")',
        f'load("{node_label("stages")}", _stages = "CLOSURES")',
        f'load("{node_label(PYTESTSPEC)}", _pytestspec = "FILES")',
        "",
        "CLOSURES = {}",
        "CLOSURES.update(_selftest)",
        "CLOSURES.update(_stages)",
        f'CLOSURES["{PYTESTSPEC}"] = _pytestspec',
        "",
        "# files the suite's own machinery reads that no stage's closure holds (BUILD, the witness, the census)",
        "EXTRA_NAMED = [",
        *[f'    "{p}",' for p in extra_named],
        "]",
    ]
    return "\n".join(lines) + "\n"


def family_nodes(leaves, family_of):
    """{family node name: [its spec leaf names]} for the per-spec leaves (the machinery belongs to none)."""
    out = {}
    for leaf in sorted(leaves):
        for family in sorted(set(family_of.values())):
            if leaf.startswith(f"{PYTESTSPEC}_{family}_"):
                out.setdefault(f"{PYTESTSPEC}_{family}", []).append(leaf)
                break
    return out


def plan_tree(closures, family_of, extra_named, specs=None, by_spec=False):
    """{repo path: file text}: the whole declaration for `closures` ({stage key: [files]}).

    `specs` is the policy-spec population (default: the keys of `family_of`). Refuses (ValueError) a spec
    with no family: a leaf needs its parent. With `by_spec` every spec is a leaf of its own and each family
    is a composite over its specs, so a port adds one leaf and edits only its family node."""
    selftest = {k: v for k, v in closures.items() if k.endswith(".py")}
    stages = {
        k: v for k, v in closures.items() if k not in selftest and k != PYTESTSPEC
    }
    leaves = partition(closures[PYTESTSPEC], family_of, specs, by_spec)
    fams = family_nodes(leaves, family_of) if by_spec else {}
    top = [MACHINERY, *sorted(fams)] if by_spec else sorted(leaves)
    out = {
        "closures.bzl": render_root(extra_named),
        node_path("selftest"): render_dict(selftest),
        node_path("stages"): render_dict(stages),
        node_path(PYTESTSPEC): render_composite(top),
    }
    for name, files in leaves.items():
        out[node_path(name)] = render_leaf(files)
    for name, kids in fams.items():
        out[node_path(name)] = render_composite(kids)
    return out


def _on_disk(root):
    return sorted(
        n for n in os.listdir(root) if n.startswith(PREFIX) and n.endswith(".bzl")
    )


def write_tree(plan, root=ROOT):
    """Write each file of `plan` whose text differs; (changed, stale): the repo paths written, and the
    closures_*.bzl files on disk that the plan no longer names (the caller removes them from git)."""
    changed = []
    for path, text in sorted(plan.items()):
        full = os.path.join(root, path)
        old = None
        if os.path.isfile(full):
            with open(full, encoding="utf-8") as fh:
                old = fh.read()
        if old == text:
            continue
        tmp = f"{full}.tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, full)
        changed.append(path)
    return changed, [p for p in _on_disk(root) if p not in plan]


def _parse(root, name):
    with open(os.path.join(root, node_path(name)), encoding="utf-8") as fh:
        return ast.parse(fh.read())


def _literal(tree, var):
    """The literal assigned to module-level `var`, or None when it is not a literal (a composition)."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == var for t in node.targets
        ):
            try:
                return ast.literal_eval(node.value)
            except ValueError:
                return None
    return None


def _children(tree):
    """The node names a file loads: the first argument of each load(":closures_NAME.bzl", ...)."""
    out = []
    for node in tree.body:
        call = node.value if isinstance(node, ast.Expr) else None
        if (
            isinstance(call, ast.Call)
            and isinstance(call.func, ast.Name)
            and call.func.id == "load"
        ):
            first = call.args[0] if call.args else None
            label = first.value if isinstance(first, ast.Constant) else ""
            if label.startswith(f":{PREFIX}") and label.endswith(".bzl"):
                out.append(label[len(f":{PREFIX}") : -len(".bzl")])
    return out


def node_files(root, name, trail=()):
    """The files a node holds: its literal FILES, or the union of its children's."""
    if name in trail:
        msg = f"{name}: a cycle through {trail}"
        raise ValueError(msg)
    tree = _parse(root, name)
    files = _literal(tree, "FILES")
    if files is not None:
        return files
    kids = _children(tree)
    if not kids:
        msg = f"{name}: neither a literal FILES nor loads of children"
        raise ValueError(msg)
    return sorted({f for k in kids for f in node_files(root, k, (*trail, name))})


def load_tree(root=ROOT):
    """{stage key: [files]} read from the tree under `root`, the shape check_closure.load_closures returns."""
    out = {}
    for kind in KINDS:
        got = _literal(_parse(root, kind), "CLOSURES")
        if not isinstance(got, dict):
            msg = f"{node_path(kind)} holds no literal CLOSURES"
            raise TypeError(msg)
        out.update(got)
    out[PYTESTSPEC] = node_files(root, PYTESTSPEC)
    return out


def nodes(root=ROOT):
    """[(node name, 'leaf'|'composite', count)] for every closures_*.bzl, in name order: a leaf's count is its
    files, a composite's its children."""
    out = []
    for fname in _on_disk(root):
        name = fname[len(PREFIX) : -len(".bzl")]
        tree = _parse(root, name)
        lit = _literal(tree, "FILES")
        kind = "leaf" if lit is not None else "composite"
        out.append((name, kind, len(lit) if lit is not None else len(_children(tree))))
    return out


def shape(root=ROOT):
    """The tree's own shape, the facts policy/closure.rego L6 and L7 decide: {nodes, dangling, orphans}.

    A DANGLING load names a node file that is not there ('node -> child'); an ORPHAN is a node file nothing
    loads (the root loads the kinds, each composite its children), so a stale leaf cannot linger unseen."""
    names = {n[len(PREFIX) : -len(".bzl")] for n in _on_disk(root)}
    with open(os.path.join(root, "closures.bzl"), encoding="utf-8") as fh:
        loaded = set(_children(ast.parse(fh.read())))
    dangling = []
    for name in sorted(names):
        for kid in _children(_parse(root, name)):
            loaded.add(kid)
            if kid not in names:
                dangling.append(f"{name} -> {kid}")
    return {
        "nodes": len(names),
        "dangling": dangling,
        "orphans": sorted(names - loaded),
    }


def main(argv):
    if argv[1:] != ["--tree"]:
        print(f"closure_tree: unknown arguments {argv[1:]!r}", file=sys.stderr)
        return 2
    found = nodes()
    if not found:
        print(
            f"closure_tree: no {PREFIX}*.bzl found; the search is broken",
            file=sys.stderr,
        )
        return 2
    for name, kind, n in found:
        print(f"{name}\t{kind}\t{n}")
    print(f"closure_tree: {len(found)} of {len(found)} node(s) read", file=sys.stderr)
    return 0


def _selftest():
    import tempfile

    ok = True

    def chk(label, got, want):
        nonlocal ok
        print(
            f"  {'ok  ' if got == want else 'FAIL'} {label}"
            + ("" if got == want else f": got {got!r} want {want!r}")
        )
        ok = ok and got == want

    fam = {"census": "gate", "tokens": "palette", "chrome": "targets"}
    chk(
        "a spec's rego, test and cases are its own; a stem that is no spec is not",
        [
            spec_of(p, fam)
            for p in (
                "policy/census.rego",
                "policy/census_test.rego",
                "policy/census.cases.json",
                "policy/zzz.rego",
                "policy/lib/fmt.rego",
                "scripts/x.py",
            )
        ],
        ["census", "census", "census", None, None, None],
    )
    files = [
        "policy/census.rego",
        "policy/census.cases.json",
        "policy/tokens.rego",
        "scripts/opa_gate.py",
        "policy/lib/truth.rego",
    ]
    chk(
        "partition: each family's spec files in its leaf, the rest in the machinery",
        partition(files, fam),
        {
            MACHINERY: ["policy/lib/truth.rego", "scripts/opa_gate.py"],
            "pytestspec_gate": ["policy/census.cases.json", "policy/census.rego"],
            "pytestspec_palette": ["policy/tokens.rego"],
        },
    )
    closures = {"scripts/check_a.py": ["a.py"], "worklist": ["w"], PYTESTSPEC: files}
    plan = plan_tree(closures, fam, ["BUILD.bazel"])
    chk(
        "plan: the root, two kinds, the pytestspec node, the machinery and two family leaves, all at the root",
        sorted(plan),
        sorted(
            [
                "closures.bzl",
                "closures_selftest.bzl",
                "closures_stages.bzl",
                "closures_pytestspec.bzl",
                "closures_pytestspec_machinery.bzl",
                "closures_pytestspec_gate.bzl",
                "closures_pytestspec_palette.bzl",
            ]
        ),
    )
    with tempfile.TemporaryDirectory() as td:
        changed, stale = write_tree(plan, td)
        chk(
            "write: every file is new on a first write, none stale",
            (len(changed), stale),
            (len(plan), []),
        )
        chk(
            "load: the tree reads back as the closures it was made from",
            load_tree(td),
            {**closures, PYTESTSPEC: sorted(files)},
        )
        chk("write: a second write changes nothing", write_tree(plan, td), ([], []))
        more = {**closures, PYTESTSPEC: [*files, "policy/census_test.rego"]}
        changed, _ = write_tree(plan_tree(more, fam, ["BUILD.bazel"]), td)
        chk(
            "a new file of a spec edits only its family's leaf: not the kinds, not the root",
            changed,
            ["closures_pytestspec_gate.bzl"],
        )
        fam2 = {**fam, "kerning": "gate"}
        grown = {**more, PYTESTSPEC: [*more[PYTESTSPEC], "policy/kerning.rego"]}
        changed, _ = write_tree(plan_tree(grown, fam2, ["BUILD.bazel"]), td)
        chk(
            "a new spec in an existing family edits only that family's leaf",
            changed,
            ["closures_pytestspec_gate.bzl"],
        )
        fam3 = {**fam2, "font": "targets"}
        wide = {**grown, PYTESTSPEC: [*grown[PYTESTSPEC], "policy/font.rego"]}
        changed, _ = write_tree(plan_tree(wide, fam3, ["BUILD.bazel"]), td)
        chk(
            "the first spec of a NEW family adds its leaf and edits the pytestspec kind (the only case that does)",
            changed,
            ["closures_pytestspec.bzl", "closures_pytestspec_targets.bzl"],
        )
        stale_plan = {
            k: v
            for k, v in plan_tree(wide, fam3, ["BUILD.bazel"]).items()
            if "palette" not in k
        }
        chk(
            "a node the plan dropped is reported stale, never silently kept",
            write_tree(stale_plan, td)[1],
            ["closures_pytestspec_palette.bzl"],
        )
        try:
            plan_tree({PYTESTSPEC: ["policy/census.rego"]}, {}, [], ["census"])
            refused = False
        except ValueError:
            refused = True
        chk(
            "a spec with no family is refused, not filed under the machinery",
            refused,
            True,
        )
    with tempfile.TemporaryDirectory() as td:
        split = {
            "closures_pytestspec.bzl": render_composite(["pytestspec_gate"]),
            "closures_pytestspec_gate.bzl": render_composite(
                ["pytestspec_gate_a", "pytestspec_gate_b"]
            ),
            "closures_pytestspec_gate_a.bzl": render_leaf(["policy/a.rego"]),
            "closures_pytestspec_gate_b.bzl": render_leaf(["policy/b.rego"]),
            "closures_selftest.bzl": render_dict({}),
            "closures_stages.bzl": render_dict({}),
        }
        write_tree(split, td)
        chk(
            "a family leaf split into children reads as the union, without changing its parent",
            load_tree(td)[PYTESTSPEC],
            ["policy/a.rego", "policy/b.rego"],
        )
    with tempfile.TemporaryDirectory() as td:
        spec_plan = plan_tree(closures, fam, ["BUILD.bazel"], by_spec=True)
        chk(
            "by spec: every spec is a leaf and each family a composite over its specs",
            sorted(spec_plan),
            sorted(
                [
                    "closures.bzl",
                    "closures_selftest.bzl",
                    "closures_stages.bzl",
                    "closures_pytestspec.bzl",
                    "closures_pytestspec_machinery.bzl",
                    "closures_pytestspec_gate.bzl",
                    "closures_pytestspec_gate_census.bzl",
                    "closures_pytestspec_palette.bzl",
                    "closures_pytestspec_palette_tokens.bzl",
                ]
            ),
        )
        write_tree(spec_plan, td)
        chk(
            "by spec: the tree reads back as the same closures",
            load_tree(td),
            {**closures, PYTESTSPEC: sorted(files)},
        )
        more = {**closures, PYTESTSPEC: [*files, "policy/census_test.rego"]}
        more_plan = plan_tree(more, fam, ["BUILD.bazel"], by_spec=True)
        chk(
            "by spec: a new file of a spec edits only that spec's leaf",
            write_tree(more_plan, td)[0],
            ["closures_pytestspec_gate_census.bzl"],
        )
        fam2 = {**fam, "kerning": "gate"}
        grown = {**more, PYTESTSPEC: [*more[PYTESTSPEC], "policy/kerning.rego"]}
        grown_plan = plan_tree(grown, fam2, ["BUILD.bazel"], by_spec=True)
        chk(
            "by spec: a new spec adds its own leaf and edits only its family composite",
            write_tree(grown_plan, td)[0],
            ["closures_pytestspec_gate.bzl", "closures_pytestspec_gate_kerning.bzl"],
        )
    with tempfile.TemporaryDirectory() as td:
        write_tree(plan, td)
        chk(
            "shape: a freshly written tree has no dangling load and no orphan",
            {k: v for k, v in shape(td).items() if k != "nodes"},
            {"dangling": [], "orphans": []},
        )
        os.remove(os.path.join(td, "closures_pytestspec_gate.bzl"))
        chk(
            "shape: a loaded node that is gone is a dangling load",
            shape(td)["dangling"],
            ["pytestspec -> pytestspec_gate"],
        )
        write_tree(plan, td)
        lost = os.path.join(td, "closures_pytestspec_lost.bzl")
        with open(lost, "w", encoding="utf-8") as fh:
            fh.write(render_leaf(["policy/lost.rego"]))
        chk(
            "shape: a node nothing loads is an orphan",
            shape(td)["orphans"],
            ["pytestspec_lost"],
        )
    live = (
        load_tree()
        if os.path.isfile(os.path.join(ROOT, node_path(PYTESTSPEC)))
        else None
    )
    if live is None:
        print(
            "  SKIP the live tree: no closures_pytestspec.bzl yet (run check_closure --compress)"
        )
    else:
        chk(
            "the live tree has the pytestspec closure (n of m, never 0 of 0)",
            len(live.get(PYTESTSPEC, [])) > 0,
            True,
        )
    print("closure_tree selftest:", "PASS" if ok else "FAIL")
    return ok


if __name__ == "__main__":
    os.chdir(ROOT)
    if sys.argv[1:] == ["--selftest"]:
        sys.exit(0 if _selftest() else 1)
    sys.exit(main(sys.argv))
